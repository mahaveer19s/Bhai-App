package com.bhai.bhai_app

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.app.Service
import android.content.Context
import android.content.Intent
import android.os.Build
import android.os.IBinder
import androidx.core.app.NotificationCompat

/**
 * Official Android-compliant Foreground Service for uninterrupted background BLE scanning.
 * Adheres to Android 8.0 through Android 15 background execution constraints using
 * FOREGROUND_SERVICE_CONNECTED_DEVICE to keep the 2.4GHz radio listener alive when minimized.
 */
class BhaiBleService : Service() {
    companion object {
        const val CHANNEL_ID = "bhai_ble_guard_channel"
        const val NOTIFICATION_ID = 1001
        const val ACTION_START = "com.bhai.app.START_GUARD"
        const val ACTION_STOP = "com.bhai.app.STOP_GUARD"

        fun start(context: Context) {
            val intent = Intent(context, BhaiBleService::class.java).apply {
                action = ACTION_START
            }
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                context.startForegroundService(intent)
            } else {
                context.startService(intent)
            }
        }

        fun stop(context: Context) {
            val intent = Intent(context, BhaiBleService::class.java).apply {
                action = ACTION_STOP
            }
            context.stopService(intent)
        }
    }

    override fun onCreate() {
        super.onCreate()
        createNotificationChannel()
    }

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        if (intent?.action == ACTION_STOP) {
            stopForeground(STOP_FOREGROUND_REMOVE)
            stopSelf()
            return START_NOT_STICKY
        }

        val launchIntent = packageManager.getLaunchIntentForPackage(packageName)
        val pendingIntent = PendingIntent.getActivity(
            this,
            0,
            launchIntent,
            PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
        )

        val notification: Notification = NotificationCompat.Builder(this, CHANNEL_ID)
            .setContentTitle("BHAI Emergency Guard Active")
            .setContentText("Scanning nearby airwaves for emergency signals.")
            .setSmallIcon(R.mipmap.ic_launcher)
            .setContentIntent(pendingIntent)
            .setOngoing(true)
            .setPriority(NotificationCompat.PRIORITY_LOW)
            .build()

        startForeground(NOTIFICATION_ID, notification)
        return START_STICKY
    }

    override fun onBind(intent: Intent?): IBinder? = null

    private fun createNotificationChannel() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            val channel = NotificationChannel(
                CHANNEL_ID,
                "BHAI Emergency Background Guard",
                NotificationManager.IMPORTANCE_LOW
            ).apply {
                description = "Keeps Bluetooth Low Energy nearby emergency detection active."
                setShowBadge(false)
            }
            val manager = getSystemService(Context.NOTIFICATION_SERVICE) as? NotificationManager
            manager?.createNotificationChannel(channel)
        }
    }
}
